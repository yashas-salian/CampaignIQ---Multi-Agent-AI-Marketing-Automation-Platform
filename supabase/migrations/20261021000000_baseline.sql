CREATE OR REPLACE FUNCTION "public"."match_embeddings"("query_embedding" "public"."vector", "match_user_id" "uuid", "match_content_type" "text", "match_count" integer) RETURNS TABLE("id" "uuid", "campaign_id" "uuid", "round_number" integer, "content_text" "text", "outcome_reward" numeric, "similarity" double precision)
    LANGUAGE "sql" STABLE
    AS $$
  select
    embeddings.id,
    embeddings.campaign_id,
    embeddings.round_number,
    embeddings.content_text,
    embeddings.outcome_reward,
    1 - (embeddings.embedding <=> query_embedding) as similarity
  from embeddings
  where embeddings.user_id = match_user_id
    and embeddings.content_type = match_content_type
  order by embeddings.embedding <=> query_embedding
  limit match_count;
$$;


