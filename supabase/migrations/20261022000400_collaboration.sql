-- Collaboration: comment threads on campaigns, and editable copy at Gate 2
-- with a full version history.

create table if not exists public.campaign_comments (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  round_number integer,                          -- null = about the campaign as a whole
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  body text not null check (char_length(trim(body)) between 1 and 4000),
  created_at timestamptz not null default now(),
  edited_at timestamptz
);
create index if not exists campaign_comments_campaign_idx on public.campaign_comments (campaign_id, created_at);
alter table public.campaign_comments enable row level security;
create policy "comments_read" on public.campaign_comments for select to authenticated
  using (public.campaign_can(campaign_id, 'view'));
create policy "comments_write" on public.campaign_comments for insert to authenticated
  with check (user_id = auth.uid() and public.campaign_can(campaign_id, 'view'));
create policy "comments_edit_own" on public.campaign_comments for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "comments_delete" on public.campaign_comments for delete to authenticated
  using (user_id = auth.uid() or public.campaign_can(campaign_id, 'manage'));
alter publication supabase_realtime add table public.campaign_comments;

-- Every version of a round's copy: the generated original plus each edit.
create table if not exists public.copy_revisions (
  id bigint generated always as identity primary key,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  round_number integer not null,
  variant text not null default 'a' check (variant in ('a', 'b')),
  copy_text text not null,
  edited_by uuid references auth.users(id) on delete set null,   -- null = generated by the AI
  created_at timestamptz not null default now()
);
create index if not exists copy_revisions_round_idx on public.copy_revisions (campaign_id, round_number, variant, id);
alter table public.copy_revisions enable row level security;
create policy "copy_revisions_read" on public.copy_revisions for select to authenticated
  using (public.campaign_can(campaign_id, 'view'));

-- Approvers edit copy while Gate 2 is open for that round.
create or replace function public.edit_round_copy(p_campaign uuid, p_round integer, p_variant text, p_text text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  current_text text;
  gate_open boolean;
begin
  if not public.campaign_can(p_campaign, 'approve') then
    raise exception 'only owners, admins and approvers can edit copy';
  end if;
  if p_variant not in ('a', 'b') then raise exception 'variant must be a or b'; end if;
  if char_length(trim(coalesce(p_text, ''))) not between 1 and 3000 then raise exception 'copy must be 1-3000 characters'; end if;
  select exists (select 1 from public.gate_decisions g where g.campaign_id = p_campaign and g.round_number = p_round
                   and g.gate_number = 2 and g.decided_at is null) into gate_open;
  if not gate_open then raise exception 'copy can only be edited while Gate 2 is open for this round'; end if;

  select case when p_variant = 'a' then i.copy_text else i.copy_text_b end into current_text
  from public.iterations i where i.campaign_id = p_campaign and i.round_number = p_round;
  -- Keep the AI's original as version 1 the first time someone edits it.
  if current_text is not null and not exists (select 1 from public.copy_revisions r
       where r.campaign_id = p_campaign and r.round_number = p_round and r.variant = p_variant) then
    insert into public.copy_revisions (campaign_id, round_number, variant, copy_text, edited_by)
    values (p_campaign, p_round, p_variant, current_text, null);
  end if;
  insert into public.copy_revisions (campaign_id, round_number, variant, copy_text, edited_by)
  values (p_campaign, p_round, p_variant, trim(p_text), auth.uid());

  if p_variant = 'a' then
    update public.iterations set copy_text = trim(p_text) where campaign_id = p_campaign and round_number = p_round;
  else
    update public.iterations set copy_text_b = trim(p_text) where campaign_id = p_campaign and round_number = p_round;
  end if;
  perform public.audit((select org_id from public.campaigns where id = p_campaign), 'copy.edited', 'campaign',
    p_campaign::text, jsonb_build_object('round', p_round, 'variant', p_variant, 'chars', char_length(trim(p_text))));
end;
$$;
revoke execute on function public.edit_round_copy(uuid, integer, text, text) from public, anon;
grant execute on function public.edit_round_copy(uuid, integer, text, text) to authenticated;
